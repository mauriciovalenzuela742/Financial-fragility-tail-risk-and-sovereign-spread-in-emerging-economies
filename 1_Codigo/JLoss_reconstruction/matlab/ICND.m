function ICNDA=ICND(u)
%    Inverse of the Cumulative Normal Distribution
    a = [2.50662823884, -18.61500062529, 41.39119773534, -25.44106049637]';
    b = [-8.4735109309, 23.08336743743, -21.06224101826, 3.13082909833]';
    c = [0.337475482272615, 0.976169019091719, 0.160797971491821, 2.76438810333863E-02, 3.8405729373609E-03, 3.951896511919E-04, 3.21767881768E-05, 2.888167364E-07, 3.960315187E-07]';
    x = u - 0.5;
    if abs(x) <= 0.42
        r = x^2;
        r = x*(a(1,1)+r*(a(2,1)+r*(a(3,1)+a(4,1)*r)))/(1+r*(b(1,1)+r*(b(2,1)+r*(b(3,1)+r*b(4,1)))));
    else
        r = u;
        if x > 0 
            r = 1 - u;
        if r == 0
            u = random('unif',0,1);
            x = u - 0.5;
            if abs(x) <= 0.42
            r = x^2;
            r = x*(a(1,1)+r*(a(2,1)+r*(a(3,1)+a(4,1)*r)))/(1+r*(b(1,1)+r*(b(2,1)+r*(b(3,1)+r*b(4,1)))));
            else
            r = u;
            if x > 0 
            r = 1 - u;
            end
            end
        end
        end
        r = log(-log(r));
        r = c(1)+r*(c(2)+r*(c(3)+r*(c(4)+ r*(c(5)+r*(c(6)+r*(c(7)+r*(c(8)+r*c(9))))))));
        if x < 0 
            r = -r;
        end
    end
        ICNDA = r;